use serde::{Deserialize, Serialize};

pub const TEXT_VERSION: &str = "2026.11.06-2";

/// Запись о принятом согласии. Живёт только в памяти запуска: согласие
/// спрашивается при каждом открытии программы и нигде не сохраняется.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AgreementRecord {
    pub accepted: bool,
    pub accepted_at: String,
    pub text_version: String,
}

impl AgreementRecord {
    pub fn accept() -> Self {
        AgreementRecord {
            accepted: true,
            accepted_at: chrono::Local::now().to_rfc3339_opts(chrono::SecondsFormat::Secs, false),
            text_version: TEXT_VERSION.to_string(),
        }
    }

    pub fn sample() -> Self {
        AgreementRecord {
            accepted: true,
            accepted_at: "2026-11-06T17:00:00".into(),
            text_version: TEXT_VERSION.to_string(),
        }
    }
}

