#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn consent_lists_every_data_class_the_code_reads() {
        let text = body();
        // Каждое место, где сканер что-то читает, должно быть описано.
        for claim in [
            "logs/latest.log",
            "launcher_profiles.json",
            "assets/",
            "accessToken",
            ".minecraft",
            "РЕЖИМ ОБХОДА ДИСКОВ",
            "имя, путь, размер и время изменения",
            "$Recycle.Bin",
            "ник, который ты",
        ] {
            assert!(text.contains(claim), "в соглашении нет про: {claim}");
        }
        assert!(!body().contains("отправит на сервер"));
    }

    #[test]
    fn consent_never_mentions_hashes() {
        let text = body().to_lowercase();
        for banned in ["sha-256", "sha256", "хэш", "хеш", "контрольную сумму"] {
            assert!(!text.contains(banned), "в соглашении упоминается {banned}");
        }
    }

    #[test]
    fn ban_warning_is_present() {
        assert!(WARNING.contains("бан"));
        assert!(body().contains("не сможет"));
    }

    #[test]
    fn record_is_tied_to_text_version() {
        assert_eq!(AgreementRecord::accept().text_version, TEXT_VERSION);
    }
}
